import type { Choice, Consequence, GameEvent, Rarity } from "../game/types";
const choice = (
  id: string,
  label: string,
  hint: string,
  consequences: Consequence,
  dispatch = false,
): Choice => ({ id, label, hint, consequences, dispatch });
const dispatch = (message: string, extra: Partial<Consequence> = {}) =>
  choice(
    "dispatch",
    "Enviar equipe",
    "Mobiliza uma unidade · consome 2% de energia",
    { danger: -5, power: -2, message, ...extra },
    true,
  );
const ignore = (message: string, danger = 9) =>
  choice(
    "ignore",
    "Encerrar sem atendimento",
    "A ocorrência ficará sem assistência",
    { danger, signal: -2, message },
  );
function routine(
  id: string,
  location: string,
  title: string,
  caller: string,
  description: string,
  resolution: string,
  advice: string,
  adviceResult: string,
  danger: number,
  rarity: Rarity = "COMMON",
  night = 1,
): GameEvent {
  return {
    id,
    location,
    title,
    caller,
    description,
    night,
    timeWindow: [12, 290],
    rarity,
    choices: [
      dispatch(resolution),
      choice(
        "advise",
        advice,
        danger > 0
          ? "Sem deslocamento · risco permanece no local"
          : "Orientação adequada · libera as unidades",
        { danger, message: adviceResult },
      ),
      ignore(
        "O chamado foi arquivado sem atendimento. A cidade ficou um pouco mais silenciosa.",
      ),
    ],
  };
}
